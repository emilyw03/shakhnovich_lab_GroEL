# Input Files

forcefield = ForceField('amber19-all.xml', 'amber19/tip3pfb.xml') # load force fields
solvatedFile = args.outdir + '/DHFR_WT_apo_solvated.pdb' # kept in the run folder so a later resume uses exactly the same atoms

if args.checkpoint is None:
    pdb = PDBFile('/n/home00/ewang03/lab/GroEL/results/openMM/DHFR_WT_apo.pdb') # load PDB file of protein generated by OpenMM setup

    # solvate molecule using OpenMM Modeller
    modeller = Modeller(pdb.topology, pdb.positions)
    modeller.addHydrogens(forcefield)
    modeller.addSolvent(forcefield, padding=1.0*nanometers, ionicStrength = 0.1*molar) # fit the smallest box around the molecule and add 1 nm padding on all sides
    PDBFile.writeFile(modeller.topology, modeller.positions, open(solvatedFile, 'w')) # save solvated molecule
else:
    # resuming: reuse the solvated structure from the checkpoint's run folder instead of re-solvating
    shutil.copy(os.path.join(os.path.dirname(os.path.abspath(args.checkpoint)), 'DHFR_WT_apo_solvated.pdb'), solvatedFile)
pdb = PDBFile(solvatedFile) # load solvated molecule

# System Configuration

nonbondedMethod = PME # method for how to treat nonbonded atoms
nonbondedCutoff = 1.0*nanometers # cutoff distance for nonbonded atoms
constraints = HBonds # additional H bond constraint
rigidWater = True # keep water rigid so water doesn't vibrate
constraintTolerance = 0.000001
#hydrogenMass = 1.5*amu
ewaldErrorTolerance = 0.0005

# Integration Options

dt = 0.002*picoseconds # want dt to be slower than the fastest fibration (1 fs for H bond)
temperature = 300*kelvin
friction = 1.0/picosecond # friction between solvent molecules
pressure = 1.0*atmospheres
barostatInterval = 25 # readjust pressure every 25 steps

# Simulation Options

steps = 50_000_000
equilibrationSteps = 1000
# StateDataReporter prints some basic info about the state of the sim to a file during the run
dataReporter = StateDataReporter(args.outdir + '/log.txt', 5000, totalSteps=steps,
    step=True, speed=True, progress=True, potentialEnergy=True, temperature=True, density=True, separator='\t') # report anything that's set to true, always print step and potentialEnergy, separator is comma or tab
xtcReporter = XTCReporter(args.outdir + '/traj.xtc', 100) # save trajectories, save every 100 steps (match with data reporter)
checkpointReporter = CheckpointReporter(args.outdir + '/checkpoint.chk', args.checkpoint_interval) # overwrite checkpoint so an interrupted run can resume exactly with --checkpoint


# Prepare the Simulation

print('Building system...')
topology = pdb.topology # topology contains information about the identity and connectivity of particles in the system (i.e., chains and residues)
positions = pdb.positions # contains coordinates of particles
system = forcefield.createSystem(topology, nonbondedMethod=nonbondedMethod, nonbondedCutoff=nonbondedCutoff,
    constraints=constraints, rigidWater=rigidWater, ewaldErrorTolerance=ewaldErrorTolerance)
system.addForce(MonteCarloBarostat(pressure, temperature, barostatInterval)) # control pressure and temp. add additional forces
integrator = LangevinMiddleIntegrator(temperature, friction, dt) # integration algorithm, defines how you go from one step to the next
integrator.setConstraintTolerance(constraintTolerance)
simulation = Simulation(topology, system, integrator) # create Simulation object to manage the simulation

if args.checkpoint is None:
    simulation.context.setPositions(positions) # context object contains info about state of simulation, including particle positions and velocities

    # Minimize and Equilibrate

    print('Performing energy minimization...')
    simulation.minimizeEnergy()
    print('Equilibrating...')
    simulation.context.setVelocitiesToTemperature(temperature)
    simulation.step(equilibrationSteps)
    simulation.currentStep = 0
else:
    print('Loading checkpoint...')
    simulation.loadCheckpoint(args.checkpoint) # restores positions, velocities, box, and currentStep

# Simulate
# Step numbers continue from the checkpoint, so log.txt / traj.xtc from each run folder can be concatenated for analysis.

remainingSteps = steps - simulation.currentStep
print(f'Simulating from step {simulation.currentStep}, {remainingSteps} steps remaining...')
simulation.reporters.append(dataReporter)
simulation.reporters.append(xtcReporter)
simulation.reporters.append(checkpointReporter)
simulation.step(remainingSteps)
simulation.saveCheckpoint(args.outdir + '/checkpoint.chk')