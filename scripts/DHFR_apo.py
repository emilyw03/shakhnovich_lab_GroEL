# DHFR_apo.py
# script for using OpenMM to simulate apo state DHFR (no small molecules)

from openmm import * # import OpenMM
# use the following to access the application layer of the Python API
from openmm.app import *
from openmm.unit import *

# command line argument parser
import argparse
import os
import shutil
parser = argparse.ArgumentParser()
parser.add_argument("outdir", type=str)
parser.add_argument("--checkpoint-interval", type=int, default=50_000) # steps between checkpoints (50,000 steps = 100 ps)
parser.add_argument("--checkpoint", type=str) # resume from this checkpoint.chk; its run folder must also hold DHFR_WT_apo_solvated.pdb
args = parser.parse_args()

